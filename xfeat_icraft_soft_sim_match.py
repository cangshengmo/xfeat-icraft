"""
Run XFeat SAR/OPT matching with ICRAFT compiled frontend models in soft simulation.

This follows the runtime quick-start soft simulation style:
  Network.CreateFromJsonFile(...)
  network.loadParamsFromFile(...)
  Session.Create([HostBackend], network.view(0), [HostDevice.Default()])
  session.forward([Tensor(input_nhwc, Layout("NHWC"))])

The frontend is deployed as two single-image compiled models:
  - xfeat_800 for optical 800x800 input
  - xfeat_512 for SAR 512x512 input

Host-side post-processing decodes sparse XFeat features, performs mutual-NN
descriptor matching, runs RANSAC and saves match visualizations.

The Python HostBackend path can run parsed/optimized/quantized/adapted stages
directly. The generated BY stage is also selectable, but the current xfeat_800
BY artifact may require ICRAFT's generated FTMP memory layout and can fail when
fed with a plain Python Tensor.
"""

