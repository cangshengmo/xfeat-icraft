def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    fieldnames = [
        "image_id",
        "stage",
        "angle_deg",
        "synthetic_scale",
        "matches",
        "inliers",
        "inlier_ratio",
        "accepted",
        "corner_rmse",
        "tx",
        "ty",
        "estimated_scale",
        "estimated_angle_deg",
        "icraft_opt_s",
        "icraft_sar_s",
        "total_s",
        "draw_path",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def print_summary(rows: list[dict[str, object]]) -> None:
    rmse = np.array([float(row["corner_rmse"]) for row in rows if not math.isnan(float(row["corner_rmse"]))])
    if len(rmse) == 0:
        print(f"Summary: cases={len(rows)}, valid=0")
        return
    print(
        "Summary: "
        f"cases={len(rows)}, valid={len(rmse)}, "
        f"<=5px={(rmse <= 5).sum()}, <=10px={(rmse <= 10).sum()}, "
        f"median={np.median(rmse):.2f}px, mean={np.mean(rmse):.2f}px"
    )
    accepted_rmse = np.array(
        [float(row["corner_rmse"]) for row in rows if int(row["accepted"]) == 1 and not math.isnan(float(row["corner_rmse"]))]
    )
    if len(accepted_rmse):
        print(
            "Accepted: "
            f"cases={len(accepted_rmse)}, <=5px={(accepted_rmse <= 5).sum()}, "
            f"<=10px={(accepted_rmse <= 10).sum()}, "
            f"median={np.median(accepted_rmse):.2f}px, mean={np.mean(accepted_rmse):.2f}px"
        )
    else:
        print("Accepted: cases=0")


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    labels = resolve_labels(args)
    angles = parse_float_list(args.angles)
    scales = parse_float_list(args.scales)
    xfeat = IcraftSoftXFeat(args)

    rows: list[dict[str, object]] = []
    for label in labels:
        for angle in angles:
            for scale in scales:
                result = run_one_case(label, angle, scale, xfeat, args)
                rows.append(result_to_row(result))
                print(
                    f"{label.image_id} angle={angle:g} scale={scale:g}: "
                    f"matches={result.matches}, inliers={result.inliers}, "
                    f"rmse={result.corner_rmse:.2f}px, "
                    f"icraft_opt={result.icraft_opt_s:.3f}s, icraft_sar={result.icraft_sar_s:.3f}s"
                )

    csv_path = args.output_dir / "xfeat_icraft_soft_sim_summary.csv"
    write_csv(csv_path, rows)
    print("")
    print(f"CSV: {csv_path}")
    print_summary(rows)


if __name__ == "__main__":
    main()
